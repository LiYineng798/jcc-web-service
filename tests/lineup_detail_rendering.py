"""Loopback fictional preview checks for detail actions and return context."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE=os.environ.get('NOTIFICATION_PREVIEW_URL','http://127.0.0.1:5160')
OUT=Path(__file__).resolve().parents[1]/'instance/lineup-detail-review'
OUT.mkdir(parents=True,exist_ok=True)

def run():
    with sync_playwright() as p:
        browser=getattr(p,os.environ.get('NOTIFICATION_BROWSER','chromium')).launch()
        ctx=browser.new_context(viewport={'width':1440,'height':1000},reduced_motion='reduce')
        ctx.add_init_script("Object.defineProperty(navigator,'clipboard',{value:{writeText:async text=>{window.copiedText=text;}}});")
        page=ctx.new_page();errors=[]
        page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto(BASE+'/lineup/48')
        expect(page.locator('#ldCopy')).to_be_enabled()
        expect(page.locator('#lineupDetailBack')).to_have_text('返回阵容库')
        expect(page.locator('#ldCode')).to_have_text('#PreviewLineup47')
        page.locator('#ldCopy').click()
        expect(page.locator('#ldActionStatus')).to_contain_text('已复制')
        assert page.evaluate('window.copiedText')=='#PreviewLineup47'
        page.locator('#ldShare').click()
        assert page.evaluate('window.copiedText')==BASE+'/lineup/48'
        page.locator('#ldFavorite').click()
        expect(page.get_by_role('link',name='登录后继续')).to_be_visible()
        page.reload()
        expect(page.locator('#ldCopy')).to_be_enabled()
        expect(page.locator('.ld-code-tag')).to_have_text('S11 · 画之灵')
        page.screenshot(path=str(OUT/'detail-desktop.png'),full_page=True,animations='disabled')
        page.set_viewport_size({'width':390,'height':844})
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        page.screenshot(path=str(OUT/'detail-mobile.png'),full_page=True,animations='disabled')
        expect(page.locator('#themeToggle')).to_have_count(0)
        page.evaluate("localStorage.setItem('theme','dark')")
        page.reload()
        expect(page.locator('html')).to_have_attribute('data-theme','dark')
        expect(page.locator('#ldCopy')).to_be_enabled()
        page.screenshot(path=str(OUT/'detail-mobile-dark.png'),full_page=True,animations='disabled')
        page.goto(BASE+'/lineup/48?return_to=https://untrusted.example/')
        expect(page.locator('#lineupDetailBack')).to_have_attribute('href','/')
        page.goto(BASE+'/lineup/48?return_to=%2Fme%23lineup-notifications')
        expect(page.locator('#lineupDetailBack')).to_have_text('返回通知')
        # Real failed clipboard and synchronization paths retain readable code.
        page.evaluate("navigator.clipboard.writeText=async()=>{throw Error('denied')};document.execCommand=()=>false")
        expect(page.locator('#ldCopy')).to_be_enabled()
        page.locator('#ldCopy').click()
        expect(page.locator('#ldSelectCode')).to_be_visible()
        page.locator('#ldSelectCode').click()
        assert page.evaluate('getSelection().toString()')=='#PreviewLineup47'
        page.goto(BASE+'/__preview__/login/user')
        page.set_viewport_size({'width':390,'height':600})
        page.locator('#lineupNotificationToggle').click()
        page.locator('.ln-filter').filter(has_text='互动').click()
        expect(page.locator('.ln-item')).to_have_count(3)
        page.locator('.ln-list').evaluate('el=>el.scrollTop=80')
        list_scroll=page.locator('.ln-list').evaluate('el=>el.scrollTop')
        page.locator('.ln-item-link').nth(1).click()
        expect(page.locator('.ln-detail .nc-action')).to_be_visible()
        page.locator('.ln-detail .nc-action').click()
        expect(page.locator('#ldCopy')).to_be_enabled()
        expect(page.locator('#lineupDetailBack')).to_have_text('返回通知')
        page.reload()
        expect(page.locator('#lineupDetailBack')).to_have_text('返回通知')
        page.locator('#lineupDetailBack').click()
        expect(page.locator('.ln-detail .nc-metrics')).to_be_visible()
        page.locator('.ln-back').click()
        expect(page.locator('.ln-item')).to_have_count(3)
        expect(page.locator('.ln-filter[aria-pressed="true"]')).to_have_text('互动')
        expect(page.locator('.ln-list')).to_have_js_property('scrollTop',list_scroll)
        page.set_viewport_size({'width':1440,'height':1000})
        page.goto(BASE+'/me#lineup-notifications')
        page.get_by_role('group',name='通知分类').get_by_role('button',name='互动',exact=True).click()
        page.locator('.pf-notice-open').first.click()
        page.get_by_role('link',name='查看阵容',exact=True).click()
        expect(page.locator('#ldCopy')).to_be_enabled()
        page.go_back()
        expect(page.locator('.pf-dialog .nc-metrics')).to_be_visible()
        page.get_by_role('button',name='返回通知列表').click()
        expect(page.locator('.pf-notice-row')).to_have_count(3)
        page.goto(BASE+'/lineup/48')
        expect(page.locator('#ldCopy')).to_be_enabled()
        if page.locator('#ldLike').is_enabled():page.locator('#ldLike').click()
        expect(page.locator('#ldLike')).to_have_attribute('aria-pressed','true')
        original=page.locator('#ldFavorite').get_attribute('aria-pressed')
        page.locator('#ldFavorite').click()
        expect(page.locator('#ldFavorite')).to_have_attribute('aria-pressed','false' if original=='true' else 'true')
        # Render the submission receipt without adding test reports to the user preview.
        page.route('**/api/lineups/48/report',lambda route:route.fulfill(json={'id':900,'feedback_id':1,'feedback_url':'/me/feedback/1','status':'pending'},status=201))
        page.locator('#ldReport').click()
        page.locator('#ldReportReason').fill('导入失败，请帮忙核实。')
        page.locator('#ldReportSubmit').click()
        expect(page.locator('#ldReportResult')).to_contain_text('反馈已收到')
        page.locator('#ldReportClose').click()
        expect(page.locator('#ldReportDialog')).not_to_be_visible()
        page.route('**/api/me',lambda route:route.abort())
        page.reload()
        expect(page.locator('#ldRetry')).to_be_visible()
        expect(page.locator('#ldCode')).to_have_text('#PreviewLineup47')
        assert not errors,errors
        browser.close()
        print('PASS: SSR detail, clipboard success/failure, login prompt, like/favorite, feedback receipt, safe return destinations, home/account notification restoration, reload, mobile/dark layout and API failure.')

if __name__=='__main__':run()
