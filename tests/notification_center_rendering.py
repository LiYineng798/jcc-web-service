"""Run against serve_notification_preview.py; mutates fictional feedback only."""
import os
import time
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE=os.environ.get('NOTIFICATION_PREVIEW_URL','http://127.0.0.1:5160')
OUT=Path(__file__).resolve().parents[1]/'instance/notification-review'
OUT.mkdir(parents=True,exist_ok=True)


def run():
    with sync_playwright() as p:
        browser=getattr(p, os.environ.get('NOTIFICATION_BROWSER','chromium')).launch()
        reply_text=f'已完成核验，谢谢你的建议。<script>这只是普通文本</script>（验证 {time.time_ns()}）'
        user=browser.new_context(viewport={'width':1440,'height':1000})
        page=user.new_page()
        errors=[]
        page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto(BASE+'/__preview__/login/user')
        page.locator('#lineupNotificationToggle').click()
        expect(page.locator('.ln-item')).to_have_count(5)
        page.screenshot(path=str(OUT/'home-inbox.png'),full_page=True,animations="disabled")
        expect(page.locator('.ln-toolbar .ln-filters')).to_have_count(1)
        expect(page.locator('.ln-item .nc-like')).to_have_count(1)
        expect(page.locator('.ln-item .nc-favorite')).to_have_count(1)
        expect(page.locator('.ln-item .nc-copy')).to_have_count(1)
        expect(page.locator('.ln-item .nc-avatar-circles img')).to_have_count(12)
        expect(page.locator('.ln-item .nc-avatar-more')).to_have_count(3)
        expect(page.locator('.ln-item .nc-avatar-more').first).to_have_text('+2')
        circles=page.locator('.ln-item .nc-avatar-circles').first.locator('.nc-avatar')
        a,b=circles.nth(0).bounding_box(),circles.nth(1).bounding_box()
        assert 14<=a['x']+a['width']-b['x']<=17,(a,b)
        page.locator('.ln-filter').filter(has_text='互动').click()
        expect(page.locator('.ln-item')).to_have_count(3)
        page.locator('.ln-list').evaluate('el=>el.scrollTop=100')
        scroll=page.locator('.ln-list').evaluate('el=>el.scrollTop')
        page.locator('.ln-item-link').first.click()
        expect(page.locator('.ln-detail .nc-metrics')).to_be_visible()
        assert page.url==BASE+'/'
        page.screenshot(path=str(OUT/'home-interaction-detail.png'),full_page=True,animations="disabled")
        page.go_back()
        expect(page.locator('.ln-item')).to_have_count(3)
        expect(page.locator('.ln-filter[aria-pressed="true"]')).to_have_text('互动')
        page.wait_for_function('(top)=>Math.abs(document.querySelector(".ln-list").scrollTop-top)<2',arg=scroll)
        page.locator('.ln-item-link').first.click()
        page.locator('.ln-back').click()
        expect(page.locator('.ln-item')).to_have_count(3)
        page.locator('.ln-filter').filter(has_text='反馈').click()
        page.locator('.ln-item-link').first.click()
        expect(page.locator('.ln-detail .nc-timeline')).to_be_visible()
        page.set_viewport_size({'width':390,'height':844})
        page.screenshot(path=str(OUT/'home-feedback-mobile.png'),full_page=True,animations="disabled")
        assert page.locator('.ln-panel').evaluate('el=>el.scrollWidth<=el.clientWidth+1')
        page.keyboard.press('Escape')
        expect(page.locator('.ln-item')).to_have_count(2)
        page.set_viewport_size({'width':1440,'height':1000})
        page.goto(BASE+'/me#lineup-notifications')
        expect(page.locator('.pf-dialog')).to_be_visible()
        expect(page.get_by_role('heading',name='通知中心',exact=True)).to_be_visible()
        expect(page.locator('.pf-notice-row')).to_have_count(5)
        page.get_by_role('button',name='互动',exact=True).click()
        expect(page.locator('.pf-notice-row')).to_have_count(3)
        circles=page.locator('.pf-notice-row .nc-avatar-circles').first.locator('.nc-avatar')
        a,b=circles.nth(0).bounding_box(),circles.nth(1).bounding_box()
        assert 14<=a['x']+a['width']-b['x']<=17,(a,b)
        page.screenshot(path=str(OUT/'account-interactions.png'),full_page=True,animations="disabled")
        page.locator('.pf-notice-open').first.click()
        expect(page.get_by_role('heading',name='收到的互动',exact=True)).to_be_visible()
        expect(page.get_by_role('link',name='查看阵容')).to_be_visible()
        page.go_back()
        expect(page.locator('.pf-notice-row')).to_have_count(3)
        expect(page.get_by_role('group',name='通知分类').get_by_role('button',name='互动',exact=True)).to_have_attribute('aria-pressed','true')
        page.locator('.pf-notice-open').first.click()
        page.get_by_role('button',name='返回通知列表').click()
        page.get_by_role('button',name='反馈',exact=True).click()
        expect(page.locator('.pf-notice-row')).to_have_count(2)
        page.locator('.pf-notice-open').first.click()
        expect(page.locator('.nc-timeline li').first).to_be_visible()
        page.screenshot(path=str(OUT/'feedback-desktop.png'),full_page=True,animations="disabled")
        page.set_viewport_size({'width':390,'height':844})
        page.screenshot(path=str(OUT/'feedback-mobile.png'),full_page=True,animations="disabled")
        assert page.locator('.pf-dialog').evaluate('el=>el.scrollWidth<=el.clientWidth+1')
        page.keyboard.press('Escape')
        expect(page.locator('.pf-notice-row')).to_have_count(2)
        page.keyboard.press('Escape')
        expect(page.locator('.pf-dialog')).to_have_count(0)

        admin=browser.new_context(viewport={'width':1440,'height':1000})
        staff=admin.new_page()
        staff.on('pageerror',lambda e:errors.append(str(e)))
        staff.goto(BASE+'/__preview__/login/admin')
        staff.locator('button[data-admin-tab="guestbook"]:visible').first.click()
        guestcard=staff.locator('.admin-card').filter(has_text='游客留言只供站长阅读')
        expect(guestcard).to_have_count(1)
        expect(guestcard.get_by_role('button',name='查看进度 / 回复用户')).to_have_count(0)
        staff.get_by_role('button',name='查看进度 / 回复用户',exact=True).first.click()
        expect(staff.locator('.fb-dialog')).to_be_visible()
        staff.get_by_label('处理进度',exact=True).select_option('resolved')
        staff.get_by_label('站内回复',exact=True).fill(reply_text)
        staff.get_by_role('button',name='发送回复 / 更新进度').click()
        expect(staff.get_by_text('已保存，用户可查看最新进度和回复。')).to_be_visible()
        staff.screenshot(path=str(OUT/'admin-reply.png'),full_page=True,animations="disabled")
        staff.set_viewport_size({'width':390,'height':844})
        staff.screenshot(path=str(OUT/'admin-reply-mobile.png'),full_page=True,animations="disabled")
        assert staff.locator('.fb-dialog').evaluate('el=>el.scrollWidth<=el.clientWidth+1')
        staff.locator('.fb-head button').click()
        expect(staff.locator('.fb-dialog')).to_have_count(0)
        staff.set_viewport_size({'width':1440,'height':1000})
        staff.locator('button[data-admin-tab="reports"]:visible').first.click()
        staff.get_by_role('button',name='已处理',exact=True).first.click()
        staff.get_by_role('button',name='查看进度 / 回复用户',exact=True).first.click()
        checkbox=staff.locator('.fb-hide input')
        checkbox.scroll_into_view_if_needed()
        box=checkbox.bounding_box()
        assert 14<=box['width']<=20 and 14<=box['height']<=20,box
        expect(staff.get_by_text('同时隐藏该阵容',exact=True)).to_be_visible()
        staff.screenshot(path=str(OUT/'admin-report-layout.png'),full_page=True,animations="disabled")
        staff.set_viewport_size({'width':390,'height':844})
        checkbox.scroll_into_view_if_needed()
        assert staff.locator('.fb-dialog').evaluate('el=>el.scrollWidth<=el.clientWidth+1')
        staff.screenshot(path=str(OUT/'admin-report-mobile.png'),full_page=True,animations="disabled")
        staff.locator('.fb-head button').click()

        page.goto(BASE+'/me#lineup-notifications')
        page.get_by_role('button',name='反馈',exact=True).click()
        page.locator('.pf-notice-row').filter(has_text='给站长的留言').locator('.pf-notice-open').click()
        expect(page.get_by_text(reply_text,exact=True)).to_be_visible()
        expect(page.locator('.nc-timeline')).to_contain_text('已解决')
        page.keyboard.press('Escape')
        page.evaluate("document.documentElement.dataset.theme='dark'")
        page.goto(BASE+'/me#lineup-notifications')
        page.evaluate("document.documentElement.dataset.theme='dark'")
        expect(page.locator('.pf-dialog')).to_be_visible()
        page.get_by_role('group',name='通知分类').get_by_role('button',name='全部',exact=True).click()
        expect(page.locator('.pf-notice-row .nc-avatar-circles img')).to_have_count(12)
        page.screenshot(path=str(OUT/'inbox-dark-mobile.png'),full_page=True,animations="disabled")
        assert not errors,errors
        browser.close()
        print('PASS: in-place details, history back, filter/scroll restoration, distinct icons, actor avatars, feedback timeline, admin reply, checkbox sizing, guest exclusion, mobile/dark layout, escaping and keyboard close; no page errors.')


if __name__=='__main__':
    run()
